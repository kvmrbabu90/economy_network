def test_edge_derived_key_resolves_to_underlying_supplies_provenance(client):
    """GET /edge/<derived key> returns the underlying supplies provenance."""
    # Find one derived customer_of key for Walmart.
    ego = client.get(f"/node/{WMT_CIK}/ego?types=customer_of").json()
    derived = next(e for e in ego["edges"] if e["attributes"]["type"] == "customer_of")
    key = derived["key"]
    underlying_id = derived["attributes"]["underlying_edge_id"]

    # Fetch the derived edge by key.
    r = client.get(f"/edge/{key}")
    assert r.status_code == 200
    body = r.json()
    assert body["attributes"]["derived"] is True
    # And the underlying supplies edge.
    r2 = client.get(f"/edge/{underlying_id}")
    assert r2.status_code == 200
    assert r2.json()["attributes"]["type"] == "supplies"
    # Their provenance snippets match.
    assert body["attributes"]["provenance"]["snippet"] == r2.json()["attributes"]["provenance"]["snippet"]


