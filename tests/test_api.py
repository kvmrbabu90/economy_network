def test_include_provisional_toggles_audit_edges(client):
    base = client.get(f"/node/{PG_CIK}/ego", params={"include_provisional": False})
    rich = client.get(f"/node/{PG_CIK}/ego", params={"include_provisional": True})
    assert base.status_code == 200 and rich.status_code == 200
    n_base = len(base.json()["edges"])
    n_rich = len(rich.json()["edges"])
    # Provisional flag must not REDUCE the result; at most expands.
    assert n_rich >= n_base
    # And the rich response should include below_threshold=true edges if PG's
    # filing named any provisional slug competitors. Sanity-check there's at
    # least one such filer in our dataset (Constellation Brands etc.):
    rich_const = client.get(
        "/node/cik:0000016918/ego",
        params={"include_provisional": True, "types": "competes_with"},
    ).json()
    has_audit = any(
        e["attributes"]["below_threshold"]
        for e in rich_const["edges"]
        if e["attributes"]["type"] == "competes_with"
    )
    assert has_audit, "expected at least one audit competes_with edge for Constellation Brands"


