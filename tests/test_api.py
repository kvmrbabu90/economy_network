def test_walmart_customer_of_derivation_matches_stored_supplies(client):
    """Walmart's ego with types=customer_of must mirror incoming supplies.

    Specifically: every derived customer_of edge with target=Walmart
    corresponds to a stored supplies edge with target=Walmart (the
    suppliers naming Walmart as their largest customer). Counts equal,
    snippets equal, no customer_of rows in the DB.
    """
    # 1) Pull the derived customer_of edges via the API.
    r = client.get(f"/node/{WMT_CIK}/ego?types=customer_of")
    assert r.status_code == 200
    derived = [
        e for e in r.json()["edges"] if e["attributes"]["type"] == "customer_of"
    ]
    assert derived, "Walmart should be a customer_of someone"
    for e in derived:
        # Each derived edge: Walmart -> supplier. Direction REVERSED from the
        # stored "supplier --supplies--> Walmart" row.
        assert e["source"] == WMT_CIK, f"derived edge source must be Walmart, got {e['source']}"
        assert e["attributes"]["derived"] is True
        assert e["attributes"]["underlying_edge_id"]
        assert e["key"].startswith("derived:customer_of:")

    # 2) Pull the stored supplies edges where Walmart is the target.
    conn = connect(DB_PATH)
    try:
        stored = conn.execute(
            "SELECT * FROM edges WHERE type = 'supplies' AND target = ? AND below_threshold = 0",
            (WMT_CIK,),
        ).fetchall()
    finally:
        conn.close()

    # Same count.
    assert len(derived) == len(stored), (
        f"derived customer_of count ({len(derived)}) must equal stored supplies "
        f"count ({len(stored)}) for Walmart"
    )
    # Same set of (supplier, Walmart) pairs and same snippets.
    derived_pairs = {
        (e["target"], e["attributes"]["provenance"]["snippet"]) for e in derived
    }
    stored_pairs = {(row["source"], row["prov_snippet"]) for row in stored}
    assert derived_pairs == stored_pairs


def test_zero_customer_of_rows_in_db(client):
    """Same as the health check, but asserted directly via SQL."""
    conn = connect(DB_PATH)
