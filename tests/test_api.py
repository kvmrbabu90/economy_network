def test_pg_ego_contains_walmart_supplies_and_regulators(client):
    r = client.get(f"/node/{PG_CIK}/ego")
    assert r.status_code == 200
    body = r.json()
    assert body["center"] == PG_CIK
    edge_types = {e["attributes"]["type"] for e in body["edges"]}
    assert "supplies" in edge_types
    assert "regulated_by" in edge_types

    # P&G --supplies--> Walmart edge must be present.
    supplies_walmart = [
        e for e in body["edges"]
        if e["attributes"]["type"] == "supplies"
        and e["source"] == PG_CIK
        and e["target"] == WMT_CIK
    ]
    assert len(supplies_walmart) == 1, (
        f"expected exactly one P&G --supplies--> Walmart edge, got {len(supplies_walmart)}"
    )
    # Provenance must be the verbatim filing snippet.
    snippet = supplies_walmart[0]["attributes"]["provenance"]["snippet"]
    assert "Walmart" in snippet

    # Regulators -- P&G is a Consumer Staples Household Products filer.
    reg_targets = {
        e["target"] for e in body["edges"]
        if e["attributes"]["type"] == "regulated_by" and e["source"] == PG_CIK
    }
    assert "regulator:sec" in reg_targets
    assert "regulator:ftc" in reg_targets


